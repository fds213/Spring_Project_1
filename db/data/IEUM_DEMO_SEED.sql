-- 11/02 전달문 8~12번: 시험 업체 전용 보완 자료. 재실행 시 같은 업무 키로 중복 생성하지 않는다.
-- IEUM_DDL.sql 및 업체·직원·계정 초기 자료 이후 실행한다.
-- 기존 팀 DB에서는 init_auth_data.sql 전체 대신 이 파일을 포함한 patches/11-02_02_DATA_PATCH.sql을 실행한다.
-- ieum0001/ieum0002에만 지점·자산·근무 지점·시험 기간을 넣는다. 실제 주소가 아닌 전달문의 시연 예시다.
-- 본사/판교지점/부산지점, 업체별 재고 장비 5개를 준비하고 추가 지점에 재고가 없으면 1개를 보충한다.
-- 기존 직원 지점·지급된 자산·유료 기간은 덮어쓰지 않는다. 자동 COMMIT하지 않는다.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    v_count PLS_INTEGER;
BEGIN
    SAVEPOINT SP_IEUM_DEMO_SEED;
    IF SYS_CONTEXT('USERENV','SESSION_USER') <> 'IEUM'
       OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'IEUM' THEN
        RAISE_APPLICATION_ERROR(-20101, 'IEUM 계정/스키마에서 실행해야 한다.');
    END IF;
    SELECT COUNT(*) INTO v_count FROM COMPANY WHERE COMPANY_CODE IN ('ieum0001','ieum0002');
    IF v_count <> 2 THEN
        RAISE_APPLICATION_ERROR(-20102, '시험 업체 ieum0001/ieum0002가 먼저 있어야 한다. init_auth_data 전체를 기존 DB에 재실행하지 말고 누락 원인을 확인한다.');
    END IF;

    MERGE INTO SUBSCRIPTION_PLAN p
    USING (SELECT 'PLAN_MONTHLY' PLAN_CODE FROM DUAL) s
    ON (p.PLAN_CODE = s.PLAN_CODE)
    WHEN MATCHED THEN UPDATE SET p.PLAN_NAME='월간', p.DURATION_MONTHS=1,
        p.MONTHLY_UNIT_PRICE=4000, p.USE_YN='Y',
        p.UPDATED_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP)
    WHEN NOT MATCHED THEN INSERT (PLAN_CODE,PLAN_NAME,DURATION_MONTHS,MONTHLY_UNIT_PRICE,USE_YN)
        VALUES (s.PLAN_CODE,'월간',1,4000,'Y');

    -- 연간 요금제. 단가는 1인 월 단가이고 할인(10%·20%)은 주문마다 서버가 계산해 남긴다.
    MERGE INTO SUBSCRIPTION_PLAN p
    USING (SELECT 'PLAN_YEARLY' PLAN_CODE FROM DUAL) s
    ON (p.PLAN_CODE = s.PLAN_CODE)
    WHEN MATCHED THEN UPDATE SET p.PLAN_NAME='연간', p.DURATION_MONTHS=12,
        p.MONTHLY_UNIT_PRICE=4000, p.USE_YN='Y',
        p.UPDATED_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP)
    WHEN NOT MATCHED THEN INSERT (PLAN_CODE,PLAN_NAME,DURATION_MONTHS,MONTHLY_UNIT_PRICE,USE_YN)
        VALUES (s.PLAN_CODE,'연간',12,4000,'Y');

    -- 기간이 하나도 없는 시험 업체만 최초 체험 기간을 만든다.
    INSERT INTO SERVICE_PERIOD (COMPANY_ID,PERIOD_TYPE,STARTS_AT,ENDS_AT,PURCHASED_SEATS,BILLING_ANCHOR_DATE)
    SELECT c.COMPANY_ID,'PD_TRIAL',TIMESTAMP '2026-10-27 00:00:00',TIMESTAMP '2026-12-01 00:00:00',10,DATE '2026-10-27'
    FROM COMPANY c
    WHERE c.COMPANY_CODE IN ('ieum0001','ieum0002')
      AND NOT EXISTS (SELECT 1 FROM SERVICE_PERIOD p WHERE p.COMPANY_ID=c.COMPANY_ID);

    -- 현재 유효한 기간이 없을 때만 가장 최근 체험 기간을 12/1까지 연장한다.
    -- 유료 기간, 과거 체험 이력, 이미 더 긴 기간은 유지한다.
    UPDATE SERVICE_PERIOD p
       SET p.ENDS_AT=TIMESTAMP '2026-12-01 00:00:00',
           p.UPDATED_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP)
     WHERE p.PERIOD_TYPE='PD_TRIAL'
       AND p.COMPANY_ID IN (SELECT COMPANY_ID FROM COMPANY WHERE COMPANY_CODE IN ('ieum0001','ieum0002'))
       AND p.STARTS_AT <= CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP)
       AND p.ENDS_AT < TIMESTAMP '2026-12-01 00:00:00'
       AND p.SERVICE_PERIOD_ID=(SELECT MAX(p2.SERVICE_PERIOD_ID) FROM SERVICE_PERIOD p2 WHERE p2.COMPANY_ID=p.COMPANY_ID AND p2.PERIOD_TYPE='PD_TRIAL')
       AND NOT EXISTS (SELECT 1 FROM SERVICE_PERIOD active_period WHERE active_period.COMPANY_ID=p.COMPANY_ID
            AND active_period.STARTS_AT <= CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP)
            AND active_period.ENDS_AT > CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP));

    INSERT INTO BRANCH (COMPANY_ID,BRANCH_NAME,ADDRESS)
    SELECT c.COMPANY_ID,b.BRANCH_NAME,b.ADDRESS
    FROM COMPANY c CROSS JOIN (
        SELECT '본사' BRANCH_NAME,'서울특별시 중구 세종대로 110' ADDRESS FROM DUAL
        UNION ALL SELECT '판교지점','경기도 성남시 분당구 판교역로 235' FROM DUAL
        UNION ALL SELECT '부산지점','부산광역시 해운대구 센텀중앙로 79' FROM DUAL
    ) b
    WHERE c.COMPANY_CODE IN ('ieum0001','ieum0002')
      AND NOT EXISTS (SELECT 1 FROM BRANCH x WHERE x.COMPANY_ID=c.COMPANY_ID AND x.BRANCH_NAME=b.BRANCH_NAME);

    -- 기존에 같은 이름으로 비활성화한 지점을 임의 활성화하지 않는다.
    SELECT COUNT(*) INTO v_count
    FROM BRANCH b JOIN COMPANY c ON c.COMPANY_ID=b.COMPANY_ID
    WHERE c.COMPANY_CODE IN ('ieum0001','ieum0002')
      AND b.BRANCH_NAME IN ('본사','판교지점','부산지점') AND b.USE_YN <> 'Y';
    IF v_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20103, '시연용 이름과 같은 비활성 지점이 있다. 지점명/활성화 여부를 담당자와 확인한다.');
    END IF;

    INSERT INTO ASSET (COMPANY_ID,ASSET_NO,ASSET_NAME,ASSET_TYPE,BRANCH_ID)
    SELECT c.COMPANY_ID,a.ASSET_NO,a.ASSET_NAME,a.ASSET_TYPE,b.BRANCH_ID
    FROM COMPANY c CROSS JOIN (
        SELECT 'LT-0001' ASSET_NO,'업무용 노트북 1' ASSET_NAME,'AT_LAPTOP' ASSET_TYPE,'본사' BRANCH_NAME FROM DUAL
        UNION ALL SELECT 'LT-0002','업무용 노트북 2','AT_LAPTOP','본사' FROM DUAL
        UNION ALL SELECT 'MN-0001','모니터 1','AT_MONITOR','본사' FROM DUAL
        UNION ALL SELECT 'LT-0003','업무용 노트북 3','AT_LAPTOP','판교지점' FROM DUAL
        UNION ALL SELECT 'LT-0004','업무용 노트북 4','AT_LAPTOP','부산지점' FROM DUAL
    ) a
    JOIN BRANCH b ON b.COMPANY_ID=c.COMPANY_ID AND b.BRANCH_NAME=a.BRANCH_NAME
    WHERE c.COMPANY_CODE IN ('ieum0001','ieum0002')
      AND NOT EXISTS (SELECT 1 FROM ASSET x WHERE x.COMPANY_ID=c.COMPANY_ID AND x.ASSET_NO=a.ASSET_NO);

    -- 기존에 다른 이름의 지점이 더 있으면 그 지점에도 미지급 재고 1개를 보충한다.
    INSERT INTO ASSET (COMPANY_ID,ASSET_NO,ASSET_NAME,ASSET_TYPE,BRANCH_ID)
    SELECT b.COMPANY_ID,'SEED-BR-'||TO_CHAR(b.BRANCH_ID),SUBSTR('시연 노트북 - '||b.BRANCH_NAME,1,200),'AT_LAPTOP',b.BRANCH_ID
    FROM BRANCH b JOIN COMPANY c ON c.COMPANY_ID=b.COMPANY_ID
    WHERE c.COMPANY_CODE IN ('ieum0001','ieum0002')
      AND NOT EXISTS (SELECT 1 FROM ASSET a WHERE a.COMPANY_ID=b.COMPANY_ID AND a.BRANCH_ID=b.BRANCH_ID)
      AND NOT EXISTS (SELECT 1 FROM ASSET a WHERE a.COMPANY_ID=b.COMPANY_ID AND a.ASSET_NO='SEED-BR-'||TO_CHAR(b.BRANCH_ID));

    UPDATE EMPLOYEE e
       SET e.BRANCH_ID=(SELECT b.BRANCH_ID FROM BRANCH b WHERE b.COMPANY_ID=e.COMPANY_ID AND b.BRANCH_NAME='본사'),
           e.UPDATED_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP)
     WHERE e.BRANCH_ID IS NULL
       AND e.COMPANY_ID IN (SELECT COMPANY_ID FROM COMPANY WHERE COMPANY_CODE IN ('ieum0001','ieum0002'));

    SELECT COUNT(DISTINCT p.COMPANY_ID) INTO v_count
    FROM SERVICE_PERIOD p JOIN COMPANY c ON c.COMPANY_ID=p.COMPANY_ID
    WHERE c.COMPANY_CODE IN ('ieum0001','ieum0002')
      AND p.STARTS_AT<=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP)
      AND p.ENDS_AT>CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP);
    IF v_count <> 2 THEN
        RAISE_APPLICATION_ERROR(-20104, '유효한 시험 이용 기간이 없는 업체가 있다. 유료 기간/미래 기간/12월 이후 시연 날짜를 수동 확인한다.');
    END IF;
    SELECT COUNT(*) INTO v_count FROM BRANCH b JOIN COMPANY c ON c.COMPANY_ID=b.COMPANY_ID
    WHERE c.COMPANY_CODE IN ('ieum0001','ieum0002')
      AND NOT EXISTS (SELECT 1 FROM ASSET a WHERE a.COMPANY_ID=b.COMPANY_ID AND a.BRANCH_ID=b.BRANCH_ID);
    IF v_count <> 0 THEN
        RAISE_APPLICATION_ERROR(-20105, '자산이 없는 지점이 남았다. 기존 시연 자산 번호의 충돌/배치 지점을 확인한다.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('시연 보완 자료 처리 완료. 점검 후 별도 COMMIT 필요.');
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK TO SP_IEUM_DEMO_SEED;
        RAISE;
END;
/

