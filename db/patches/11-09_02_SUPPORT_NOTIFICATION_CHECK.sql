-- 이음 장애 문의 답변 알림 사후 점검. 조회만 수행하며 COMMIT하지 않는다.
SET DEFINE OFF

SELECT '1 문의 컬럼 NUMBER(19)·NULL 허용' AS ITEM,
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END AS RESULT
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND COLUMN_NAME = 'SUPPORT_INQUIRY_ID'
   AND DATA_TYPE = 'NUMBER'
   AND DATA_PRECISION = 19
   AND DATA_SCALE = 0
   AND NULLABLE = 'Y'
UNION ALL
SELECT '2 같은 업체 문의 FK',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND CONSTRAINT_NAME = 'FK_69_08'
   AND CONSTRAINT_TYPE = 'R'
   AND R_OWNER = USER
   AND R_CONSTRAINT_NAME = 'UQ_74_01'
   AND STATUS = 'ENABLED'
   AND VALIDATED = 'VALIDATED'
UNION ALL
SELECT '3 문의 조회 인덱스',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_INDEXES
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND INDEX_NAME = 'IX_69_07'
   AND UNIQUENESS = 'NONUNIQUE'
   AND STATUS = 'VALID'
UNION ALL
SELECT '4 알림 대상 CHECK 활성·검증과 네 분기',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND CONSTRAINT_NAME = 'CK_69_01'
   AND STATUS = 'ENABLED'
   AND VALIDATED = 'VALIDATED'
   AND SEARCH_CONDITION_VC LIKE '%NT_APPROVAL_REQUEST%'
   AND SEARCH_CONDITION_VC LIKE '%NT_TICKET_ASSIGNED%'
   AND SEARCH_CONDITION_VC LIKE '%NT_ATT_CORRECTION_REQUEST%'
   AND SEARCH_CONDITION_VC LIKE '%NT_SUPPORT_REPLY%'
UNION ALL
SELECT '5 문의 답변 알림 코드',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM COMMON_CODE
 WHERE CODE = 'NT_SUPPORT_REPLY'
   AND PARENT_CODE = 'NOTIFICATION_TYPE'
   AND USE_YN = 'Y'
   AND SORT_ORDER = 8
UNION ALL
SELECT '6 공통 코드 233개 이상',
       CASE WHEN COUNT(*) >= 233 THEN 'PASS' ELSE 'FAIL' END
  FROM COMMON_CODE;

-- CHECK의 네 분기가 패치와 일치하는지 확인한다.
SELECT SEARCH_CONDITION_VC
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND CONSTRAINT_NAME = 'CK_69_01';

-- FK 컬럼 순서가 COMPANY_ID, SUPPORT_INQUIRY_ID인지 확인한다.
SELECT COLUMN_NAME, POSITION
  FROM USER_CONS_COLUMNS
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND CONSTRAINT_NAME = 'FK_69_08'
 ORDER BY POSITION;

-- 인덱스 컬럼 순서가 COMPANY_ID, SUPPORT_INQUIRY_ID인지 확인한다.
SELECT COLUMN_NAME, COLUMN_POSITION
  FROM USER_IND_COLUMNS
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND INDEX_NAME = 'IX_69_07'
 ORDER BY COLUMN_POSITION;
