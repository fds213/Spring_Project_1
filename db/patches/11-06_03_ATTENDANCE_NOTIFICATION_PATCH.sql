-- 근태 정정 알림: 기존 DB 전용 1회 패치.
-- 별도 실행 승인 후 관련 쓰기를 멈추고 미확정 작업이 없는 연결에서 실행한다.
-- DDL은 자동 확정된다. 일부 실패 시 상태 확인 없이 다시 실행하지 않는다.

SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

-- 이미 적용된 구조와 예상하지 않은 기존 상태에서는 중단한다.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'NOTIFICATION'
       AND COLUMN_NAME = 'ATTENDANCE_CORRECTION_ID';

    IF v_count <> 0 THEN
        RAISE_APPLICATION_ERROR(-20001, '알림 정정 컬럼이 이미 있습니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'ATTENDANCE_CORRECTION'
       AND CONSTRAINT_NAME = 'UQ_82_01'
       AND CONSTRAINT_TYPE = 'U'
       AND STATUS = 'ENABLED'
       AND VALIDATED = 'VALIDATED';

    IF v_count <> 1 THEN
        RAISE_APPLICATION_ERROR(-20002, '참조 대상 UQ_82_01을 확인하세요.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'NOTIFICATION'
       AND CONSTRAINT_NAME = 'CK_69_01'
       AND CONSTRAINT_TYPE = 'C'
       AND STATUS = 'ENABLED'
       AND VALIDATED = 'VALIDATED';

    IF v_count <> 1 THEN
        RAISE_APPLICATION_ERROR(-20003, '기존 CK_69_01 상태가 예상과 다릅니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_NAME = 'FK_69_07';

    IF v_count <> 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'FK_69_07이 이미 있습니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_OBJECTS
     WHERE OBJECT_NAME = 'IX_69_06';

    IF v_count <> 0 THEN
        RAISE_APPLICATION_ERROR(-20005, 'IX_69_06 이름이 이미 사용 중입니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM COMMON_CODE
     WHERE CODE = 'NOTIFICATION_TYPE';

    IF v_count <> 1 THEN
        RAISE_APPLICATION_ERROR(-20006, '상위 코드 NOTIFICATION_TYPE이 없습니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM COMMON_CODE
     WHERE CODE IN (
         'NT_ATT_CORRECTION_REQUEST',
         'NT_ATT_CORRECTION_DONE'
     );

    IF v_count <> 0 THEN
        RAISE_APPLICATION_ERROR(-20007, '정정 알림 코드가 이미 있습니다.');
    END IF;
END;
/

ALTER TABLE NOTIFICATION ADD (
    ATTENDANCE_CORRECTION_ID NUMBER(19)
);

COMMENT ON COLUMN NOTIFICATION.ATTENDANCE_CORRECTION_ID IS '근태 정정 요청';

-- 같은 업체의 근태 정정 요청만 참조한다.
ALTER TABLE NOTIFICATION ADD CONSTRAINT FK_69_07
    FOREIGN KEY (COMPANY_ID, ATTENDANCE_CORRECTION_ID)
    REFERENCES ATTENDANCE_CORRECTION (
        COMPANY_ID, ATTENDANCE_CORRECTION_ID
    );

CREATE INDEX IX_69_06 ON NOTIFICATION (
    COMPANY_ID, ATTENDANCE_CORRECTION_ID
);

ALTER TABLE NOTIFICATION DROP CONSTRAINT CK_69_01;

ALTER TABLE NOTIFICATION ADD CONSTRAINT CK_69_01 CHECK (
    (NOTIFICATION_TYPE IN (
        'NT_APPROVAL_REQUEST', 'NT_APPROVAL_DONE', 'NT_APPROVAL_REJECT'
    )
        AND APPROVAL_DOCUMENT_ID IS NOT NULL
        AND IT_TICKET_ID IS NULL
        AND ATTENDANCE_CORRECTION_ID IS NULL)
 OR (NOTIFICATION_TYPE IN (
        'NT_TICKET_ASSIGNED', 'NT_TICKET_RESOLVED'
    )
        AND IT_TICKET_ID IS NOT NULL
        AND APPROVAL_DOCUMENT_ID IS NULL
        AND ATTENDANCE_CORRECTION_ID IS NULL)
 OR (NOTIFICATION_TYPE IN (
        'NT_ATT_CORRECTION_REQUEST', 'NT_ATT_CORRECTION_DONE'
    )
        AND ATTENDANCE_CORRECTION_ID IS NOT NULL
        AND APPROVAL_DOCUMENT_ID IS NULL
        AND IT_TICKET_ID IS NULL)
);

-- DML은 모든 DDL 뒤에 수행한다.
INSERT INTO COMMON_CODE (
    CODE, PARENT_CODE, CODE_NAME, DESCRIPTION, USE_YN, SORT_ORDER
)
SELECT 'NT_ATT_CORRECTION_REQUEST',
