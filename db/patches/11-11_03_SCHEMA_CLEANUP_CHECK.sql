        'SQ_SUPPORT_REPLY', 'SQ_ATTENDANCE_CORRECTION'
    );
    v_count PLS_INTEGER;
    v_failed BOOLEAN := FALSE;

    PROCEDURE check_count(p_label VARCHAR2, p_actual PLS_INTEGER, p_expected PLS_INTEGER) IS
    BEGIN
        IF p_actual = p_expected THEN
            DBMS_OUTPUT.PUT_LINE('PASS: ' || p_label || ' = ' || p_actual);
        ELSE
            DBMS_OUTPUT.PUT_LINE('FAIL: ' || p_label || ' = ' || p_actual || ' (기대값 ' || p_expected || ')');
            v_failed := TRUE;
        END IF;
    END;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'IEUM'
       OR SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> 'IEUM' THEN
        RAISE_APPLICATION_ERROR(-20601, 'IEUM 계정과 IEUM 스키마에서 실행하세요.');
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TABLES
     WHERE TABLE_NAME IN (SELECT COLUMN_VALUE FROM TABLE(c_keep_tables));
    check_count('유지 테이블', v_count, 60);

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME IN (SELECT COLUMN_VALUE FROM TABLE(c_keep_tables));
    check_count('유지 컬럼', v_count, 615);

    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_TYPE = 'R' AND STATUS = 'ENABLED' AND VALIDATED = 'VALIDATED'
       AND TABLE_NAME IN (SELECT COLUMN_VALUE FROM TABLE(c_keep_tables));
    check_count('활성·검증된 외래키', v_count, 231);

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES
     WHERE SEQUENCE_NAME IN (SELECT COLUMN_VALUE FROM TABLE(c_keep_sequences))
       AND MAX_VALUE = 99999 AND CYCLE_FLAG = 'N';
    check_count('시퀀스 (MAXVALUE 99999 / NOCYCLE)', v_count, 50);

    SELECT COUNT(*) INTO v_count FROM USER_TABLES
     WHERE TABLE_NAME IN (SELECT COLUMN_VALUE FROM TABLE(c_drop_tables));
    check_count('제외 대상 중 남은 테이블', v_count, 0);

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES
     WHERE SEQUENCE_NAME IN (SELECT COLUMN_VALUE FROM TABLE(c_drop_sequences));
    check_count('제외 대상 중 남은 시퀀스', v_count, 0);

    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS
     WHERE TABLE_NAME IN (SELECT COLUMN_VALUE FROM TABLE(c_keep_tables))
       AND (STATUS <> 'ENABLED' OR VALIDATED <> 'VALIDATED');
    check_count('비활성·미검증 제약', v_count, 0);

    IF v_failed THEN
        RAISE_APPLICATION_ERROR(-20606, '기대값과 다른 항목을 확인하세요.');
    END IF;
END;
