        'SERVICE_PERIOD', 'CAPACITY_REQUEST', 'PAYMENT_ORDER', 'PAYMENT',
        'SUBSCRIPTION_CHANGE', 'CAPACITY_LIMIT', 'APPROVAL_DOCUMENT', 'APPROVAL_STEP',
