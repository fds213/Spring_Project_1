        'SQ_COMPANY', 'SQ_DEPARTMENT', 'SQ_JOB_GRADE', 'SQ_BRANCH',
        'SQ_EMPLOYEE', 'SQ_USER_ACCOUNT', 'SQ_ACCOUNT_REQUEST', 'SQ_EMAIL_VERIFICATION',
