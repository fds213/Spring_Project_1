-- 연차 추가 부여 사후 점검. 조회만 수행하며 COMMIT하지 않는다.
SET DEFINE OFF

SELECT '1 NOTE 문자형·500자·NULL 허용' AS ITEM,
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END AS RESULT
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME = 'LEAVE_LEDGER'
   AND COLUMN_NAME = 'NOTE'
   AND DATA_TYPE = 'VARCHAR2'
   AND CHAR_LENGTH = 500
   AND CHAR_USED = 'C'
   AND NULLABLE = 'Y'

UNION ALL

SELECT '2 휴가 신청일 NULL 허용',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME = 'LEAVE_LEDGER'
   AND COLUMN_NAME = 'LEAVE_REQUEST_DAY_ID'
   AND NULLABLE = 'Y'

UNION ALL

SELECT '3 기존 고유 제약 제거',
       CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'LEAVE_LEDGER'
   AND CONSTRAINT_NAME = 'UQ_33_01'

UNION ALL

SELECT '4 조건부 고유 인덱스 상태',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_INDEXES
 WHERE TABLE_NAME = 'LEAVE_LEDGER'
   AND INDEX_NAME = 'UX_33_01'
   AND UNIQUENESS = 'UNIQUE'
   AND INDEX_TYPE = 'FUNCTION-BASED NORMAL'
   AND STATUS = 'VALID'

UNION ALL

SELECT '5 CHECK 제약 두 개 활성·검증',
       CASE WHEN COUNT(*) = 2 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'LEAVE_LEDGER'
   AND CONSTRAINT_NAME IN ('CK_33_01', 'CK_33_02')
   AND STATUS = 'ENABLED'
   AND VALIDATED = 'VALIDATED'

UNION ALL

SELECT '6 추가 부여 코드',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM COMMON_CODE
 WHERE CODE = 'LC_GRANT'
   AND PARENT_CODE = 'LEAVE_CHANGE'
   AND CODE_NAME = '추가 부여'
   AND USE_YN = 'Y'
   AND SORT_ORDER = 3

UNION ALL

SELECT '7 공통 코드 230개 이상',
       CASE WHEN COUNT(*) >= 230 THEN 'PASS' ELSE 'FAIL' END
  FROM COMMON_CODE

UNION ALL

SELECT '8 기존 FK 다섯 개 유지',
       CASE WHEN COUNT(*) = 5 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'LEAVE_LEDGER'
   AND CONSTRAINT_NAME IN (
       'FK_33_01', 'FK_33_02', 'FK_33_03', 'FK_33_04', 'FK_33_05'
   )
   AND CONSTRAINT_TYPE = 'R'
   AND STATUS = 'ENABLED'
   AND VALIDATED = 'VALIDATED';

