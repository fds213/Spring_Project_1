-- 이음 장애 문의 답변 알림: 기존 DB 전용 1회 패치.
-- 별도 실행 승인 후 관련 쓰기를 멈추고 미확정 작업이 없는 연결에서 실행한다.
-- DDL은 자동 확정된다. 일부 실패 시 상태 확인 없이 다시 실행하지 않는다.

SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

-- 다른 연결이 알림을 저장하는 순간과 겹쳐도 바로 실패하지 않고 30초까지 기다린다.
ALTER SESSION SET DDL_LOCK_TIMEOUT = 30;

-- 이미 적용된 구조와 예상하지 않은 기존 상태에서는 아무것도 바꾸지 않고 중단한다.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'NOTIFICATION'
       AND COLUMN_NAME = 'SUPPORT_INQUIRY_ID';

    IF v_count <> 0 THEN
        RAISE_APPLICATION_ERROR(-20001, '알림 문의 컬럼이 이미 있습니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'NOTIFICATION'
       AND COLUMN_NAME = 'ATTENDANCE_CORRECTION_ID';

    IF v_count <> 1 THEN
        RAISE_APPLICATION_ERROR(-20002, '11-06_03 근태 정정 알림 패치가 먼저 필요합니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'SUPPORT_INQUIRY'
       AND CONSTRAINT_NAME = 'UQ_74_01'
       AND CONSTRAINT_TYPE = 'U'
       AND STATUS = 'ENABLED'
       AND VALIDATED = 'VALIDATED';

    IF v_count <> 1 THEN
        RAISE_APPLICATION_ERROR(-20003, '참조 대상 UQ_74_01을 확인하세요.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'NOTIFICATION'
       AND CONSTRAINT_NAME = 'CK_69_01'
       AND CONSTRAINT_TYPE = 'C'
       AND STATUS = 'ENABLED'
       AND VALIDATED = 'VALIDATED'
       AND SEARCH_CONDITION_VC LIKE '%NT_ATT_CORRECTION_REQUEST%'
       AND SEARCH_CONDITION_VC NOT LIKE '%NT_SUPPORT_REPLY%';

    IF v_count <> 1 THEN
        RAISE_APPLICATION_ERROR(-20004, '기존 CK_69_01 상태가 예상과 다릅니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_NAME = 'FK_69_08';

    IF v_count <> 0 THEN
        RAISE_APPLICATION_ERROR(-20005, 'FK_69_08이 이미 있습니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_OBJECTS
     WHERE OBJECT_NAME = 'IX_69_07';

    IF v_count <> 0 THEN
        RAISE_APPLICATION_ERROR(-20006, 'IX_69_07 이름이 이미 사용 중입니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM COMMON_CODE
     WHERE CODE = 'NOTIFICATION_TYPE';

    IF v_count <> 1 THEN
        RAISE_APPLICATION_ERROR(-20007, '상위 코드 NOTIFICATION_TYPE이 없습니다.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM COMMON_CODE
     WHERE CODE = 'NT_SUPPORT_REPLY'
        OR (PARENT_CODE = 'NOTIFICATION_TYPE' AND SORT_ORDER = 8);

    IF v_count <> 0 THEN
        RAISE_APPLICATION_ERROR(-20008, '문의 답변 코드나 정렬 순서 8번이 이미 있습니다.');
    END IF;
END;
/

ALTER TABLE NOTIFICATION ADD (
    SUPPORT_INQUIRY_ID NUMBER(19)
);

COMMENT ON COLUMN NOTIFICATION.SUPPORT_INQUIRY_ID IS '이음 장애 문의';

-- 같은 업체의 장애 문의만 참조한다.
ALTER TABLE NOTIFICATION ADD CONSTRAINT FK_69_08
    FOREIGN KEY (COMPANY_ID, SUPPORT_INQUIRY_ID)
    REFERENCES SUPPORT_INQUIRY (
        COMPANY_ID, SUPPORT_INQUIRY_ID
    );

CREATE INDEX IX_69_07 ON NOTIFICATION (
    COMPANY_ID, SUPPORT_INQUIRY_ID
);

ALTER TABLE NOTIFICATION DROP CONSTRAINT CK_69_01;

ALTER TABLE NOTIFICATION ADD CONSTRAINT CK_69_01 CHECK (
    (NOTIFICATION_TYPE IN (
        'NT_APPROVAL_REQUEST', 'NT_APPROVAL_DONE', 'NT_APPROVAL_REJECT'
    )
        AND APPROVAL_DOCUMENT_ID IS NOT NULL
        AND IT_TICKET_ID IS NULL
        AND ATTENDANCE_CORRECTION_ID IS NULL
        AND SUPPORT_INQUIRY_ID IS NULL)
 OR (NOTIFICATION_TYPE IN (
        'NT_TICKET_ASSIGNED', 'NT_TICKET_RESOLVED'
    )
        AND IT_TICKET_ID IS NOT NULL
        AND APPROVAL_DOCUMENT_ID IS NULL
        AND ATTENDANCE_CORRECTION_ID IS NULL
        AND SUPPORT_INQUIRY_ID IS NULL)
 OR (NOTIFICATION_TYPE IN (
        'NT_ATT_CORRECTION_REQUEST', 'NT_ATT_CORRECTION_DONE'
    )
        AND ATTENDANCE_CORRECTION_ID IS NOT NULL
        AND APPROVAL_DOCUMENT_ID IS NULL
        AND IT_TICKET_ID IS NULL
        AND SUPPORT_INQUIRY_ID IS NULL)
 OR (NOTIFICATION_TYPE = 'NT_SUPPORT_REPLY'
        AND SUPPORT_INQUIRY_ID IS NOT NULL
        AND APPROVAL_DOCUMENT_ID IS NULL
        AND IT_TICKET_ID IS NULL
        AND ATTENDANCE_CORRECTION_ID IS NULL)
);

-- DML은 모든 DDL 뒤에 수행한다.
INSERT INTO COMMON_CODE (
    CODE, PARENT_CODE, CODE_NAME, DESCRIPTION, USE_YN, SORT_ORDER
)
SELECT 'NT_SUPPORT_REPLY',
       'NOTIFICATION_TYPE',
       '이음 문의 답변',
       '운영자가 이음 장애 문의에 답변했음을 문의한 직원에게 알리는 알림',
       'Y',
       8
  FROM DUAL
 WHERE NOT EXISTS (
    SELECT 1 FROM COMMON_CODE
     WHERE CODE = 'NT_SUPPORT_REPLY'
);

