CREATE SEQUENCE SQ_ATTENDANCE_CORRECTION START WITH 1000 INCREMENT BY 1 MAXVALUE 99999 NOCYCLE CACHE 20;

CREATE TABLE ATTENDANCE_CORRECTION (
    ATTENDANCE_CORRECTION_ID NUMBER(19) DEFAULT SQ_ATTENDANCE_CORRECTION.NEXTVAL NOT NULL,
    COMPANY_ID NUMBER(19) NOT NULL,
    EMPLOYEE_ID NUMBER(19) NOT NULL,
    WORK_DATE DATE NOT NULL,
    ATTENDANCE_ID NUMBER(19),
    ORIGIN_CHECK_IN_AT TIMESTAMP(6),
    ORIGIN_CHECK_OUT_AT TIMESTAMP(6),
    REQ_CHECK_IN_AT TIMESTAMP(6),
    REQ_CHECK_OUT_AT TIMESTAMP(6) NOT NULL,
    REASON VARCHAR2(500 CHAR) NOT NULL,
    STATUS_CODE VARCHAR2(40 CHAR) DEFAULT 'ACR_REQUESTED' NOT NULL,
    APPROVER_EMPLOYEE_ID NUMBER(19),
    DECIDED_AT TIMESTAMP(6),
    REJECT_REASON VARCHAR2(500 CHAR),
    CREATED_AT TIMESTAMP(6) DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP) NOT NULL,
    UPDATED_AT TIMESTAMP(6) DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP) NOT NULL,
    CONSTRAINT PK_ATTENDANCE_CORRECTION PRIMARY KEY (ATTENDANCE_CORRECTION_ID),
    CONSTRAINT UQ_82_01 UNIQUE (COMPANY_ID, ATTENDANCE_CORRECTION_ID),
    CONSTRAINT CK_82_01 CHECK (WORK_DATE = TRUNC(WORK_DATE)),
    -- 요청 시각은 그 근무일 안, 퇴근은 출근보다 늦게 (ATTENDANCE 의 CK_36_01·02 와 같은 규칙)
    CONSTRAINT CK_82_02 CHECK (TRUNC(CAST(REQ_CHECK_OUT_AT AS DATE)) = WORK_DATE),
    CONSTRAINT CK_82_03 CHECK (REQ_CHECK_IN_AT IS NULL OR (TRUNC(CAST(REQ_CHECK_IN_AT AS DATE)) = WORK_DATE AND REQ_CHECK_OUT_AT >= REQ_CHECK_IN_AT)),
    CONSTRAINT CK_82_04 CHECK (STATUS_CODE IN ('ACR_REQUESTED','ACR_APPROVED','ACR_REJECTED','ACR_CANCELED')),
    -- 승인·반려면 처리자와 처리 일시가 있어야 하고, 반려면 사유가 있어야 한다
    CONSTRAINT CK_82_05 CHECK (STATUS_CODE NOT IN ('ACR_APPROVED','ACR_REJECTED') OR (APPROVER_EMPLOYEE_ID IS NOT NULL AND DECIDED_AT IS NOT NULL)),
    CONSTRAINT CK_82_06 CHECK (STATUS_CODE <> 'ACR_REJECTED' OR REJECT_REASON IS NOT NULL),
    -- 결근 정정(그날 근태 행이 없음)은 출근 시각도 요청해야 한다
    CONSTRAINT CK_82_07 CHECK (ATTENDANCE_ID IS NOT NULL OR REQ_CHECK_IN_AT IS NOT NULL),
    CONSTRAINT CK_82_08 CHECK (ORIGIN_CHECK_IN_AT IS NULL OR REQ_CHECK_OUT_AT >= ORIGIN_CHECK_IN_AT)
);
COMMENT ON TABLE ATTENDANCE_CORRECTION IS '근태 정정 요청';
