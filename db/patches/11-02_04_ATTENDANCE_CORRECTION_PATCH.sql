    END IF;
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME IN ('COMPANY','EMPLOYEE','ATTENDANCE','COMMON_CODE');
    IF n<>4 THEN RAISE_APPLICATION_ERROR(-20502,'기본 테이블이 부족하다.'); END IF;
    SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME IN ('ATTENDANCE_CORRECTION','SQ_ATTENDANCE_CORRECTION','PK_ATTENDANCE_CORRECTION','UQ_82_01','UX_82_01','IX_82_01','IX_82_02');
