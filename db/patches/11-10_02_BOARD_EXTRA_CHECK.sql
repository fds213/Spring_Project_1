-- 익명 게시판·자료실 사후 점검. 조회만 수행하며 COMMIT하지 않는다.
SET DEFINE OFF

SELECT '1 게시판 CHECK 활성·검증과 네 종류' AS ITEM,
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END AS RESULT
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'BOARD'
   AND CONSTRAINT_NAME = 'CK_52_01'
   AND CONSTRAINT_TYPE = 'C'
   AND STATUS = 'ENABLED'
   AND VALIDATED = 'VALIDATED'
   AND SEARCH_CONDITION_VC LIKE '%BOARD_NOTICE%'
   AND SEARCH_CONDITION_VC LIKE '%BOARD_DEPT%'
   AND SEARCH_CONDITION_VC LIKE '%BOARD_ANON%'
   AND SEARCH_CONDITION_VC LIKE '%BOARD_LIBRARY%'
UNION ALL
SELECT '2 익명 게시판 코드',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM COMMON_CODE
 WHERE CODE = 'BOARD_ANON'
   AND PARENT_CODE = 'BOARD_TYPE'
   AND CODE_NAME = '익명 게시판'
   AND USE_YN = 'Y'
   AND SORT_ORDER = 3
UNION ALL
SELECT '3 자료실 코드',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM COMMON_CODE
 WHERE CODE = 'BOARD_LIBRARY'
   AND PARENT_CODE = 'BOARD_TYPE'
   AND CODE_NAME = '자료실'
   AND USE_YN = 'Y'
   AND SORT_ORDER = 4
UNION ALL
SELECT '4 전사 공지·부서 게시판 코드 유지',
       CASE WHEN COUNT(*) = 2 THEN 'PASS' ELSE 'FAIL' END
  FROM COMMON_CODE
 WHERE PARENT_CODE = 'BOARD_TYPE'
   AND ((CODE = 'BOARD_NOTICE' AND SORT_ORDER = 1)
        OR (CODE = 'BOARD_DEPT' AND SORT_ORDER = 2))
UNION ALL
SELECT '5 공통 코드 235개 이상',
       CASE WHEN COUNT(*) >= 235 THEN 'PASS' ELSE 'FAIL' END
  FROM COMMON_CODE
UNION ALL
SELECT '6 임시 제약 CK_52_01_TMP가 남지 않음',
       CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_CONSTRAINTS
 WHERE CONSTRAINT_NAME = 'CK_52_01_TMP';

-- CHECK의 두 분기가 패치와 일치하는지 확인한다.
-- 공지·익명·자료실은 DEPARTMENT_ID IS NULL, 부서 게시판만 IS NOT NULL이어야 한다.
SELECT SEARCH_CONDITION_VC
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'BOARD'
   AND CONSTRAINT_NAME = 'CK_52_01';

-- 게시판 종류 코드 네 개를 확인한다.
SELECT CODE, CODE_NAME, USE_YN, SORT_ORDER
  FROM COMMON_CODE
 WHERE PARENT_CODE = 'BOARD_TYPE'
 ORDER BY SORT_ORDER;
