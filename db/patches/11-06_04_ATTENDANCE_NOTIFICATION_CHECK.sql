-- 근태 정정 알림 사후 점검. 조회만 수행하며 COMMIT하지 않는다.
SET DEFINE OFF

SELECT '1 정정 요청 컬럼 NUMBER(19)·NULL 허용' AS ITEM,
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END AS RESULT
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND COLUMN_NAME = 'ATTENDANCE_CORRECTION_ID'
   AND DATA_TYPE = 'NUMBER'
   AND DATA_PRECISION = 19
   AND DATA_SCALE = 0
   AND NULLABLE = 'Y'

UNION ALL

SELECT '2 같은 업체 정정 요청 FK',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND CONSTRAINT_NAME = 'FK_69_07'
   AND CONSTRAINT_TYPE = 'R'
   AND R_OWNER = USER
   AND R_CONSTRAINT_NAME = 'UQ_82_01'
   AND STATUS = 'ENABLED'
   AND VALIDATED = 'VALIDATED'

UNION ALL

SELECT '3 정정 요청 조회 인덱스',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_INDEXES
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND INDEX_NAME = 'IX_69_06'
   AND UNIQUENESS = 'NONUNIQUE'
   AND STATUS = 'VALID'

UNION ALL

SELECT '4 알림 대상 CHECK 활성·검증',
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'NOTIFICATION'
   AND CONSTRAINT_NAME = 'CK_69_01'
   AND STATUS = 'ENABLED'
   AND VALIDATED = 'VALIDATED'

UNION ALL

SELECT '5 정정 알림 코드 두 개',
       CASE WHEN COUNT(*) = 2 THEN 'PASS' ELSE 'FAIL' END
  FROM COMMON_CODE
 WHERE PARENT_CODE = 'NOTIFICATION_TYPE'
   AND USE_YN = 'Y'
   AND (
       (CODE = 'NT_ATT_CORRECTION_REQUEST' AND SORT_ORDER = 6)
       OR (CODE = 'NT_ATT_CORRECTION_DONE' AND SORT_ORDER = 7)
   )

UNION ALL

SELECT '6 공통 코드 232개 이상',
       CASE WHEN COUNT(*) >= 232 THEN 'PASS' ELSE 'FAIL' END
  FROM COMMON_CODE;

