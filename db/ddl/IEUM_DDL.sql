CREATE TABLE COMMON_CODE (
    CODE VARCHAR2(40 CHAR) NOT NULL,
    PARENT_CODE VARCHAR2(40 CHAR),
    CODE_NAME VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    USE_YN CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    SORT_ORDER NUMBER(5) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP) NOT NULL,
    UPDATED_AT TIMESTAMP(6) DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP) NOT NULL,
    CONSTRAINT PK_COMMON_CODE PRIMARY KEY (CODE),
    CONSTRAINT CK_01_01 CHECK (SORT_ORDER >= 0),
    CONSTRAINT CK_01_02 CHECK (PARENT_CODE IS NULL OR PARENT_CODE <> CODE),
    CONSTRAINT CK_01_03 CHECK (USE_YN IN ('Y','N'))
);
COMMENT ON TABLE COMMON_CODE IS '공통 코드';
COMMENT ON COLUMN COMMON_CODE.CODE IS '공통코드';
